<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class OrderInvoice extends Model
{
    /*
    |--------------------------------------------------------------------------
    | CONFIGURACIÓN
    |--------------------------------------------------------------------------
    */

    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | RELACIONES
        |--------------------------------------------------------------------------
        */

        'order_id',

        /*
        |--------------------------------------------------------------------------
        | DOCUMENTO
        |--------------------------------------------------------------------------
        */

        'document_type',
        'document_number',

        /*
        |--------------------------------------------------------------------------
        | CLIENTE
        |--------------------------------------------------------------------------
        */

        'customer_name',
        'company_name',

        /*
        |--------------------------------------------------------------------------
        | CONTACTO
        |--------------------------------------------------------------------------
        */

        'email',
        'phone',

        /*
        |--------------------------------------------------------------------------
        | UBICACIÓN
        |--------------------------------------------------------------------------
        */

        'address',
        'city',

        /*
        |--------------------------------------------------------------------------
        | INFORMACIÓN TRIBUTARIA
        |--------------------------------------------------------------------------
        */

        'tax_regime',
        'tax_responsibility',

        /*
        |--------------------------------------------------------------------------
        | FACTURA
        |--------------------------------------------------------------------------
        */

        'is_generated',
        'invoice_number',
        'generated_at',

        /*
        |--------------------------------------------------------------------------
        | OBSERVACIONES
        |--------------------------------------------------------------------------
        */

        'notes',
    ];

    protected $casts = [

        'is_generated' => 'boolean',

        'generated_at' => 'datetime',
    ];

    /*
    |--------------------------------------------------------------------------
    | RELACIONES
    |--------------------------------------------------------------------------
    */

    public function order()
    {
        return $this->belongsTo(
            Order::class
        );
    }

    /*
    |--------------------------------------------------------------------------
    | HELPERS
    |--------------------------------------------------------------------------
    */

    public function getDocumentAttribute()
    {
        return trim(
            "{$this->document_type} {$this->document_number}"
        );
    }

    public function getStatusBadgeAttribute()
    {
        return $this->is_generated
            ? [
                'text' => 'Facturada',
                'color' => 'success',
            ]
            : [
                'text' => 'Pendiente',
                'color' => 'warning',
            ];
    }
}